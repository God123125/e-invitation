/** Converts western digits to Khmer numerals (0 -> ០, 1 -> ១, etc.) */
export function toKhmerNumerals(num: number | string): string {
  const kmDigits = ["០", "១", "២", "៣", "៤", "៥", "៦", "៧", "៨", "៩"];
  return String(num).replace(/[0-9]/g, (digit) => kmDigits[Number(digit)]);
}
